export type Nutrition = {
  kcal: number;
  protein: number;
  fat: number;
  carbs: number;
};
export type Unit = "г" | "мл" | "шт";
export type Ingredient = {
  id: string;
  name: string;
  amount: number;
  unit: Unit;
  gramsPerUnit: number;
  category: string;
  nutrition: Nutrition;
  source: string;
};
export type Recipe = {
  id: string;
  name: string;
  description: string;
  category: string;
  proteinGroup: string;
  minutes: number;
  difficulty: "Легко" | "Средне";
  equipment: string;
  cost: number;
  servings: number;
  yield: number;
  yieldMeasured: boolean;
  image: string;
  ingredients: Ingredient[];
  steps: string[];
  substitutions: string;
  tags: string[];
  allergens: string[];
  source: string;
};
export type Feedback = {
  rating: number;
  reaction: "" | "like" | "dislike" | "try";
  favorite: boolean;
  cooked: boolean;
  reasons: string[];
  notes: string;
  comfort?: "small" | "right" | "large";
};
export type Profile = {
  name: string;
  goal: string;
  kcal: number;
  protein: number;
  fat: number;
  carbs: number;
  mealProtein: number;
  weeklyServings: number;
  noPork: boolean;
  dislikes: string;
  allergens: string;
  spices: string;
  budget: number;
  maxMinutes: number;
  difficulty: string;
  defaultServings: number;
  equipment: string[];
  fatMode: "auto" | "manual";
  fatShare: number;
  plateLimit: number;
  novelty: "balanced" | "familiar" | "new";
};
export type Meal = {
  id: string;
  date: string;
  slot: string;
  recipeId: string;
  servings: number;
  recipeSnapshot?: Recipe;
  menuId?: string;
  people?: number;
};
export type PantryItem = {
  id: string;
  name: string;
  amount: number;
  unit: Unit;
  expires: string;
};
export type ShoppingItem = {
  id: string;
  name: string;
  amount: number;
  unit: Unit;
  category: string;
  checked: boolean;
};
export type FoodState = {
  version: 2;
  profile: Profile;
  feedback: Record<string, Feedback>;
  recipes: Recipe[];
  hidden: string[];
  plan: Meal[];
  consumed: Meal[];
  pantry: PantryItem[];
  shopping: ShoppingItem[];
  wizard: MenuDraft | null;
  menuHistory: MenuRevision[];
  recipeHistory: RecipeRevision[];
  priceQuotes: PriceQuote[];
  shoppingSettings: ShoppingSettings;
  stockEvents: string[];
};

export type Slot = "Завтрак" | "Обед" | "Ужин";
export type Targets = Nutrition;
export type MealChoice = {
  recipe: Recipe;
  factor: number;
  batchPortions: number;
  approvedAt: string;
};
export type MenuDraft = {
  id: string;
  startDate: string;
  days: number;
  people: number;
  equipment: string[];
  targets: Targets;
  fatMode: "auto" | "manual";
  fatShare: number;
  plateLimit: number;
  choices: Partial<Record<Slot, MealChoice>>;
  rejected: string[];
  offered: string[];
  step: number;
};
export type MenuRevision = {
  id: string;
  createdAt: string;
  label: string;
  draft: MenuDraft;
  meals: Meal[];
};
export type RecipeRevision = { id: string; createdAt: string; recipe: Recipe };
export type PriceQuote = {
  id: string;
  name: string;
  store: string;
  city: string;
  location: string;
  packAmount: number;
  unit: Unit;
  price: number;
  observedAt: string;
  source: string;
  kind: "manual" | "estimate" | "feed";
  condition?: "regular" | "loyalty" | "promo";
  conditions?: string;
  validUntil: string;
};
export type ShoppingSettings = {
  city: string;
  location: string;
  stores: string[];
  mode: "one-store" | "cheapest";
  delivery: number;
  maxStores: number;
  chosenStores: string[];
  loyaltyStores: string[];
};
